def generate_circle_bitmap():
    bitmap = Bitmap(240, 240, 1)
    bitmap.PALETTE = [BLACK, WHITE]  # 设置调色板
    
    # 绘制中心圆 (半径100)
    center_x, center_y = 120, 120
    radius = 100
    
    # Bresenham画圆算法
    f = 1 - radius
    ddf_x = 1
    ddf_y = -2 * radius
    x = 0
    y = radius
    
    # 初始点
    bitmap.set_pixel(center_x, center_y + radius, 1)
    bitmap.set_pixel(center_x, center_y - radius, 1)
    bitmap.set_pixel(center_x + radius, center_y, 1)
    bitmap.set_pixel(center_x - radius, center_y, 1)
    
    while x < y:
        if f >= 0:
            y -= 1
            ddf_y += 2
            f += ddf_y
        x += 1
        ddf_x += 2
        f += ddf_x
        
        # 绘制8个对称点
        positions = [
            (x, y), (-x, y), (x, -y), (-x, -y),
            (y, x), (-y, x), (y, -x), (-y, -x)
        ]
        
        for dx, dy in positions:
            bitmap.set_pixel(center_x + dx, center_y + dy, 1)
    
    return bitmap

