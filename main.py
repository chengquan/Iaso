def generate_grayscale_rgb565():
    grayscale = []
    for i in range(256):
        # 将0-255线性映射到RGB565的亮度
        intensity = int(i * 31 / 255)
        # RGB565格式：RRRRRGGGGGGBBBBB
        color = (intensity << 11) | (intensity << 5) | intensity
        grayscale.append(color)
    return grayscale


