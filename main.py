def frame_to_bitmaps(frame_buffer, var_name="_BITMAPS1"):
    """
    将uarray帧缓冲转换为Python字节串格式
    参数:
        frame_buffer: uarray.array('B')类型的一维数组
        var_name: 生成的变量名(默认为_BITMAPS1)
    返回:
        可执行的Python赋值语句字符串
    """
    # 方法1：直接转换（推荐）
    def chunks(data, size):
        for i in range(0, len(data), size):
            yield data[i:i+size]
    
    hex_lines = []
    for chunk in chunks(frame_buffer, 16):
        hex_lines.append("    b'" + "".join(f"\\x{b:02x}" for b in chunk) + "'\\")
    
    return f"{var_name} =\\\n" + "\n".join(hex_lines).rstrip('\\')


